"""Rebuild conf/sector_members.yaml from the booster pages already recorded.

stockmojo's booster lists, for each sector, the F&O stocks in it. That list is
the only thing this experiment still needs from stockmojo for sector
selection (the % changes come from Dhan), and it barely changes, so it is kept
as a file: the union of every snapshot in data/*/booster.csv. Re-run it now
and then (a new F&O listing, an index rebalance):

    python3 scripts/refresh_sector_members.py
"""
import csv
from collections import defaultdict
from pathlib import Path

EXP = Path(__file__).resolve().parent.parent

members: dict[str, set] = defaultdict(set)
days = []
for path in sorted((EXP / "data").glob("*/booster.csv")):
    days.append(path.parent.name)
    with path.open() as fh:
        for r in csv.DictReader(fh):
            members[r["sector"]].add(r["symbol"])

out = EXP / "conf" / "sector_members.yaml"
with out.open("w") as fh:
    fh.write("# Generated by scripts/refresh_sector_members.py -- do not edit by hand.\n")
    fh.write(f"# Source: stockmojo intraday-booster sector cards recorded on {', '.join(days)}.\n")
    fh.write("# Each sector's F&O stocks; their % changes come from Dhan, not from here.\n")
    for sector in sorted(members):
        fh.write(f'"{sector}": [{", ".join(sorted(members[sector]))}]\n')
print(f"{out}: {len(members)} sectors, {sum(len(v) for v in members.values())} memberships from {days}")
